alter table public.assignments
add column if not exists assignment_code text,
add column if not exists category text not null default 'Thánh học căn bản';

create unique index if not exists assignments_assignment_code_unique_idx
on public.assignments (lower(assignment_code))
where assignment_code is not null and btrim(assignment_code) <> '';

create table if not exists public.assignment_questions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  question_type text not null default 'multiple_choice'
    check (question_type in ('multiple_choice', 'essay')),
  prompt text not null,
  helper_text text,
  scripture_reference text,
  answer_hint text,
  points numeric not null default 1 check (points >= 0),
  sort_order integer not null default 1 check (sort_order > 0),
  is_required boolean not null default true,
  allow_multiple boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists assignment_questions_assignment_order_idx
on public.assignment_questions (assignment_id, sort_order);

create table if not exists public.assignment_question_options (
  id bigint generated by default as identity primary key,
  question_id bigint not null references public.assignment_questions(id) on delete cascade,
  option_text text not null,
  is_correct boolean not null default false,
  sort_order integer not null default 1 check (sort_order > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists assignment_question_options_question_order_idx
on public.assignment_question_options (question_id, sort_order);
